// Regenerate after adding or changing a registry entry: node scripts/gen-provider-display.mjs
import { writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import REGISTRY from "../open-sse/providers/registry/index.js";
import { MEDIA_ONLY_ALIASES } from "../open-sse/services/model.js";

/** Build shell display and alias data without retaining registry transports or model lists. */
export function buildProviderDisplay(registry) {
  const providers = {};
  const aliases = { ...MEDIA_ONLY_ALIASES };
  const uiAliases = {};
  for (const entry of registry) {
    if (entry.display) {
      providers[entry.id] = {
        category: entry.category,
        name: entry.display.name,
        color: entry.display.color,
        ...(entry.display.textIcon ? { textIcon: entry.display.textIcon } : {}),
      };
    } else {
      providers[entry.id] = { category: entry.category, display: false };
    }
    aliases[entry.id] = entry.id;
    if (entry.alias) aliases[entry.alias] = entry.id;
    for (const alias of entry.aliases || []) aliases[alias] = entry.id;
    if (entry.uiAlias) uiAliases[entry.uiAlias] = entry.id;
  }
  return { providers, aliases, uiAliases };
}

/** Render committed ESM snapshot used by shell components. */
export function renderProviderDisplay(registry) {
  const { providers, aliases, uiAliases } = buildProviderDisplay(registry);
  const key = (name) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name));
  const lines = (value) =>
    Object.entries(value)
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([name, entry]) => `  ${key(name)}: ${JSON.stringify(entry)},`)
      .join("\n");
  return `// Generated by node scripts/gen-provider-display.mjs. Do not edit by hand.\n// biome-ignore format: machine-generated diff-friendly snapshot\n/** Minimal registry display data for dashboard shell. */\nexport const PROVIDER_DISPLAY = {\n${lines(providers)}\n};\n\n/** Router provider aliases, including registry ids. */\nexport const PROVIDER_ALIASES = {\n${lines(aliases)}\n};\n\n/** Dashboard-only short aliases (used after router aliases). */\nexport const PROVIDER_UI_ALIASES = {\n${lines(uiAliases)}\n};\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await writeFile(
    fileURLToPath(new URL("../src/shared/constants/providerDisplay.generated.js", import.meta.url)),
    renderProviderDisplay(REGISTRY),
  );
}
